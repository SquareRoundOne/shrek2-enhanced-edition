r"""Builds installer/Shrek2EE_Setup.iss (Inno Setup 6) from the working game folder.
usage: mkinstaller.py <working game folder> <manifest.json from payloaddiff.py> [version]

Layers of the installer:
  1. the base package (rel0933 scripts + its payload + fresh builds from out/): unpacked into the game folder,
     then System\ShrekRemaster\install.ps1 does what it always did (backups, ini repair, DPI, launcher language)
  2. the packs outside System: HD textures, levels, sound effects, music, videos (the manifest of payloaddiff.py,
     without the Sounds\AllDialog voice files - the launcher's language manager makes those from lang\)
  3. System\ShrekRemaster\lang: English and Russian text, voices, textures, videos (state.ini is written by Setup)
  4. DXVK (d3d8.dll, d3d9.dll, dxvk.conf from the working folder)
Originals the packs overwrite go to System\ShrekRemaster\backup_packs\ first; Uninstall puts them back.
packs.lst (installed beside the others) lists the files of layers 2 and 4 for that."""
import json, os, sys

GAME = sys.argv[1].rstrip('/\\') + os.sep
MAN = json.load(open(sys.argv[2], encoding='utf-8'))
VER = sys.argv[3] if len(sys.argv) > 3 else '0.9.73'
HERE = os.path.dirname(os.path.abspath(__file__))
PROJ = os.path.dirname(HERE)
OUT = os.path.join(PROJ, 'installer'); os.makedirs(OUT, exist_ok=True)
SYS = GAME + 'System' + os.sep

assets_ico = os.path.join(PROJ, 'assets', 'Shrek2EE.ico')
files = []   # (source, destination dir under {app}, flags)
def add(src, dest, flags='ignoreversion'):
    files.append((src, dest, flags))

# 1. base package
R = os.path.join(PROJ, 'rel0933') + os.sep
for root, _, fs in os.walk(R):
    for f in fs:
        p = os.path.join(root, f); rel = os.path.relpath(root, R)
        add(p, '{app}' if rel == '.' else '{app}\\' + rel)
pay = SYS + 'ShrekRemaster' + os.sep + 'files' + os.sep
have = {os.path.relpath(os.path.join(r, f), R).replace(os.sep, '/') for r, _, fs in os.walk(R) for f in fs}
O = os.path.join(PROJ, 'out') + os.sep
fresh = {'dinput8.dll': O + 'dinput8.dll', 'shrz.dll': O + 'shrz.dll', 'SHGame.u': SYS + 'SHGame.u', 'KWGame.u': SYS + 'KWGame.u'}
for root, _, fs in os.walk(pay):
    for f in fs:
        rel = os.path.relpath(os.path.join(root, f), pay)
        if rel == 'SHHDFonts.utx' or rel in fresh or ('System/ShrekRemaster/files/' + rel.replace(os.sep, '/')) in have:
            continue
        d = os.path.dirname(rel)
        add(os.path.join(root, f), '{app}\\System\\ShrekRemaster\\files' + ('\\' + d if d else ''))
# the untouched Russian originals install.ps1 -Uninstall puts back (rel0933 keeps only the small ones)
orig = SYS + 'ShrekRemaster' + os.sep + 'original' + os.sep
for f in sorted(os.listdir(orig)):
    if ('System/ShrekRemaster/original/' + f) not in have:
        add(orig + f, '{app}\\System\\ShrekRemaster\\original')
for k, v in fresh.items():
    add(v, '{app}\\System\\ShrekRemaster\\files')
add(assets_ico, '{app}\System\ShrekRemaster')   # the shortcuts' icon
add(O + 'Shrek2EE.exe', '{app}')          # renamed below
files[-1] = (files[-1][0], '{app}', 'ignoreversion; DestName: "Shrek 2 Enhanced Edition.exe"')

# 2. packs (never the voice packs: lang\ and the launcher make those)
packs = []
for e in MAN:
    p = e['path']
    if p.lower().startswith('sounds\\alldialog') or p.lower() == 'ru_list.txt':
        continue
    packs.append(p)
    d = os.path.dirname(p)
    add(GAME + p, '{app}' + ('\\' + d if d else ''), 'ignoreversion uninsneveruninstall')   # Uninstall puts the originals back itself

# 3. lang
LANG = SYS + 'ShrekRemaster' + os.sep + 'lang' + os.sep
for root, _, fs in os.walk(LANG):
    for f in fs:
        if f.lower() == 'state.ini':
            continue
        rel = os.path.relpath(root, LANG)
        add(os.path.join(root, f), '{app}\\System\\ShrekRemaster\\lang' + ('' if rel == '.' else '\\' + rel))

# 4. DXVK
dxvk = ['System\\d3d8.dll', 'System\\d3d9.dll', 'System\\dxvk.conf']
for p in dxvk:
    if os.path.exists(GAME + p):
        packs.append(p); add(GAME + p, '{app}\\System', 'ignoreversion uninsneveruninstall')
    else:
        print('missing', p)

with open(os.path.join(OUT, 'packs.lst'), 'w', encoding='utf-8') as f:
    f.write('\n'.join(packs) + '\n')

assets = os.path.join(PROJ, 'assets') + os.sep
